for (const [verb, [forms, context]] of Object.entries(present)) {
  const examples = data[verb]?.examples?.["Présent"];
  if (!examples || examples.length !== forms.length) throw new Error(`${verb}: invalid present inventory`);
  examples.forEach((example, index) => { example.ar = `${forms[index]} ${context}.`; });
}

const replacements = [
  [/هذا الفشل/gu, "هذا العطل"],
  [/هذا الانقطاع/gu, "هذا العطل"],
  [/تحريك الجدول/gu, "تحريك الطاولة"],
  [/قمت بسحب الستار/gu, "سحبت الستارة"],
  [/قمت بسحب الستارة/gu, "سحبت الستارة"],
  [/حساب المشاركين/gu, "عدّ المشاركين"],
  [/الأخبار السارة/gu, "الخبر السار"]
];

for (const record of Object.values(data)) {
  for (const examples of Object.values(record.examples)) {
    for (const example of examples) {
      for (const [pattern, replacement] of replacements) example.ar = example.ar.replace(pattern, replacement);
      example.ar = example.ar.replace(/\s+([،.!؟])/gu, "$1").trim();
    }
  }
}

fs.writeFileSync(dataPath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
